function pickProblems(){
	const pool = PROBLEM_POOL.slice();
	const picked = [];
	const count = Math.min(4, pool.length);
	for (let i = 0; i < count; i++){
		const idx = Math.floor(Math.random() * pool.length);
		picked.push(pool.splice(idx, 1)[0]);
	}
	return picked;
}
